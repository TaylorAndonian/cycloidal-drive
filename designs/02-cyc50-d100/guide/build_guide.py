#!/usr/bin/env python3
"""Assemble assembly-guide.html: concatenate the three HTML parts and inline the
step drawings as scalable SVG (matplotlib output, cleaned up for embedding)."""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
REN  = os.path.join(HERE, "..", "renders")

def clean_svg(path):
    s = open(path, encoding="utf-8").read()
    s = re.sub(r"<\?xml[^>]*\?>", "", s)
    s = re.sub(r"<!DOCTYPE[^>]*>", "", s, flags=re.I)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"<metadata>.*?</metadata>", "", s, flags=re.S)
    # drop the fixed pt size so the drawing scales to its container; keep viewBox
    s = re.sub(r'(<svg\b[^>]*?)\swidth="[^"]*"', r"\1", s, count=1)
    s = re.sub(r'(<svg\b[^>]*?)\sheight="[^"]*"', r"\1", s, count=1)
    return s.strip()

html = []
for part in ("part1.html", "part2.html", "part3.html"):
    html.append(open(os.path.join(HERE, part), encoding="utf-8").read())
doc = "<!-- cycloidal-50-d100 assembly guide, generated by guide/build_guide.py -->\n" + "\n".join(html)

for n in range(1, 9):
    svg = clean_svg(os.path.join(REN, "step_%d.svg" % n))
    token = "{{DWG_%d}}" % n
    assert token in doc, "missing placeholder " + token
    doc = doc.replace(token, svg)

assert "{{" not in doc, "unreplaced placeholder remains"
out = os.path.join(HERE, "..", "assembly-guide.html")
open(out, "w", encoding="utf-8").write(doc)
print("wrote %s  (%.0f KB)" % (out, len(doc.encode("utf-8"))/1024))
